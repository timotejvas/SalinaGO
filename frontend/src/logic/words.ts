// No React and no map here, only data.

export type Lang = "en" | "cs";

// A Czech noun after a number: 1 vozidlo, 2 vozidla, 5 vozidel.
function czech(count: number, one: string, few: string, many: string): string {
  if (count === 1) return one;
  if (count >= 2 && count <= 4) return few;
  return many;
}

